"""Finite identity/SQL/calibration examples; Python 3.11+ standard library.

This script uses an independent in-memory table and exact arithmetic. It does
not import measurement_import or treat that implementation as an oracle.
"""
from contextlib import closing
from fractions import Fraction
import json
import sqlite3

ROWS = [("a", 0, 2), ("b", 1000, 4), ("c", 2000, 6), ("d", 3000, 8)]


def describe(values):
    values = [Fraction(value) for value in values]
    n = len(values)
    if not n:
        return {"n": 0, "mean_mV": None, "pvariance_mV2": None,
                "variance_mV2": None, "rms2_mV2": None}
    mean = sum(values) / n
    centered = sum((value - mean) ** 2 for value in values)
    return {"n": n, "mean_mV": str(mean),
            "pvariance_mV2": str(centered / n),
            "variance_mV2": str(centered / (n - 1)) if n > 1 else None,
            "rms2_mV2": str(sum(value * value for value in values) / n)}


def main():
    with closing(sqlite3.connect(":memory:")) as connection:
        connection.execute("CREATE TABLE samples (sample_id TEXT PRIMARY KEY, "
                           "tick_ms INTEGER NOT NULL, code INTEGER NOT NULL)")
        connection.executemany("INSERT INTO samples VALUES (?, ?, ?)", ROWS)
        identities = connection.execute(
            "SELECT sample_id,tick_ms,code FROM samples ORDER BY sample_id").fetchall()
        groups = connection.execute(
            "SELECT code % 4 AS bucket, COUNT(*), SUM(code) FROM samples "
            "GROUP BY code % 4 ORDER BY bucket").fetchall()
        aggregate = connection.execute(
            "SELECT COUNT(*),SUM(code),AVG(code) FROM samples").fetchone()
        window = connection.execute(
            "SELECT sample_id,code,COUNT(*) OVER (),AVG(code) OVER () "
            "FROM samples ORDER BY sample_id").fetchall()
        high = connection.execute(
            "SELECT sample_id,tick_ms,code FROM samples WHERE code>=6 "
            "ORDER BY sample_id").fetchall()
    # Expected finite row sets and outputs are literal, not generated by SQL.
    assert identities == ROWS
    assert groups == [(0, 2, 12), (2, 2, 8)]
    assert aggregate == (4, 20, 5.0)
    assert window == [("a", 2, 4, 5.0), ("b", 4, 4, 5.0),
                      ("c", 6, 4, 5.0), ("d", 8, 4, 5.0)]
    assert high == [("c", 2000, 6), ("d", 3000, 8)]
    # Model identity replay independently from the importer, then check literals.
    accepted = {}
    inserted = duplicates = read = 0
    for _ in range(500):
        for identity, tick, code in ROWS:
            read += 1
            if identity in accepted:
                assert accepted[identity] == (tick, code)
                duplicates += 1
            else:
                accepted[identity] = (tick, code)
                inserted += 1
    assert (read, inserted, duplicates, len(accepted)) == (2000, 4, 1996, 4)
    result = {"identities": identities, "groups": groups, "aggregate": aggregate,
              "window": window, "high_rows": high,
              "full": describe([2, 4, 6, 8]), "committed_prefix": describe([2, 4]),
              "high": describe([6, 8]), "identity_policy": describe([2, 6]),
              "distinct_ids_same_code": describe([2, 2]),
              "one_id_replay": describe([2]), "empty": describe([]),
              "calibration_2q_plus_3": describe([7, 11, 15, 19]),
              "replay_500_event_counts": {"read": read, "inserted": inserted,
                                           "duplicates": duplicates, "final_rows": len(accepted)}}
    expected = {"full": ("5", "5", "20/3", "30"),
                "committed_prefix": ("3", "1", "2", "10"),
                "high": ("7", "1", "2", "50"),
                "identity_policy": ("4", "4", "8", "20"),
                "calibration_2q_plus_3": ("13", "20", "80/3", "189")}
    for name, values in expected.items():
        got = result[name]
        assert tuple(got[key] for key in ("mean_mV", "pvariance_mV2",
                    "variance_mV2", "rms2_mV2")) == values, name
    assert result["distinct_ids_same_code"]["n"] == 2
    assert result["distinct_ids_same_code"]["pvariance_mV2"] == "0"
    assert result["one_id_replay"]["variance_mV2"] is None
    assert result["empty"]["mean_mV"] is None
    print(json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
