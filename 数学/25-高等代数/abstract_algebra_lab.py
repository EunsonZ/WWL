"""Exact small examples; enumeration does not prove general algebra theorems.

Permutations are tuples of images of 0,...,n-1; compose(a,b) acts by b first.
Groups have at most 12 elements; no third-party dependency is used.
"""
from fractions import Fraction
from itertools import permutations
from math import gcd, isqrt
from pathlib import Path
import argparse
import json


def integer(value):
    if type(value) is not int:
        raise ValueError("expected an integer (booleans/floats are invalid)")
    return value


def permutation(value):
    if not isinstance(value, tuple) or not 1 <= len(value) <= 8:
        raise ValueError("permutation must be a tuple of length 1..8")
    if any(type(v) is not int for v in value) or sorted(value) != list(range(len(value))):
        raise ValueError("images must be exactly 0,...,n-1")
    return value


def compose(a, b):
    a, b = permutation(a), permutation(b)
    if len(a) != len(b):
        raise ValueError("permutation degrees differ")
    return tuple(a[b[i]] for i in range(len(a)))


def inverse(a):
    a = permutation(a)
    return tuple(a.index(i) for i in range(len(a)))


class FiniteGroup:
    def __init__(self, elements):
        supplied = tuple(elements)
        if not supplied or len(supplied) > 12:
            raise ValueError("group must have 1..12 supplied elements")
        for p in supplied:
            permutation(p)
        if len({len(p) for p in supplied}) != 1:
            raise ValueError("permutation degrees differ")
        self.elements = frozenset(supplied)
        self.identity = tuple(range(len(supplied[0])))
        if self.identity not in self.elements:
            raise ValueError("identity missing")
        if any(compose(a, b) not in self.elements for a in self.elements for b in self.elements):
            raise ValueError("elements are not closed")
        # Associativity comes from permutations; finite closure with identity
        # also supplies inverses. Check explicitly to aid input diagnostics.
        if any(inverse(a) not in self.elements for a in self.elements):
            raise ValueError("inverse missing")

    def generated(self, generators):
        supplied = tuple(generators)
        for g in supplied:
            permutation(g)
            if g not in self.elements:
                raise ValueError("generator outside group")
        h = {self.identity}
        pending = [self.identity]
        while pending:
            a = pending.pop()
            for g in supplied:
                b = compose(a, g)
                if b not in h:
                    h.add(b)
                    pending.append(b)
        return frozenset(h)

    def subgroup(self, h):
        h = frozenset(h)
        for g in h:
            permutation(g)
        if not h or not h <= self.elements or self.identity not in h:
            raise ValueError("invalid subgroup elements")
        if any(compose(a, inverse(b)) not in h for a in h for b in h):
            raise ValueError("set is not a subgroup")
        return h

    def all_subgroups(self):
        # Every subgroup is generated by its elements. Add one generator at
        # a time; this reaches them all without assuming a Sylow theorem.
        found = {frozenset({self.identity})}
        pending = list(found)
        while pending:
            h = pending.pop()
            for g in sorted(self.elements - h):
                k = self.generated(tuple(sorted(h)) + (g,))
                if k not in found:
                    found.add(k)
                    pending.append(k)
        return tuple(sorted(found, key=lambda h: (len(h), sorted(h))))

    def left_cosets(self, h):
        h = self.subgroup(h)
        unseen, answer = set(self.elements), []
        while unseen:
            g = min(unseen)
            coset = frozenset(compose(g, x) for x in h)
            answer.append(coset)
            unseen.difference_update(coset)
        return tuple(answer)

    def is_normal(self, h):
        h = self.subgroup(h)
        return all(frozenset(compose(compose(g, x), inverse(g)) for x in h) == h
                   for g in self.elements)

    def quotient_table(self, h):
        h = self.subgroup(h)
        if not self.is_normal(h):
            raise ValueError("quotient multiplication requires a normal subgroup")
        cosets = self.left_cosets(h)
        index = {g: i for i, c in enumerate(cosets) for g in c}
        reps = [min(c) for c in cosets]
        return tuple(tuple(index[compose(a, b)] for b in reps) for a in reps)

    def sylow(self, p):
        p = integer(p)
        if p < 2 or p > 10000 or any(p % d == 0 for d in range(2, isqrt(p) + 1)):
            raise ValueError("p must be prime in the example range 2..10000")
        order, target = len(self.elements), 1
        while order % p == 0:
            order //= p
            target *= p
        # If p does not divide |G|, the trivial subgroup is the Sylow p-group.
        return tuple(h for h in self.all_subgroups() if len(h) == target)


def examples():
    s3 = FiniteGroup(permutations(range(3)))
    r, s = (1, 2, 3, 0), (0, 3, 2, 1)
    # r^k s^epsilon, with the square's vertices numbered counterclockwise.
    rotations, a = [], tuple(range(4))
    for _ in range(4):
        rotations.append(a)
        a = compose(r, a)
    d4 = FiniteGroup([compose(a, b) for a in rotations for b in (tuple(range(4)), s)])
    return s3, d4, r, s


def pair(z):
    if not isinstance(z, tuple) or len(z) != 2:
        raise ValueError("expected an integer coefficient pair")
    return tuple(integer(v) for v in z)


def gaussian_mul(z, w):
    a, b = pair(z)
    c, d = pair(w)
    return a*c - b*d, a*d + b*c


def gaussian_norm(z):
    a, b = pair(z)
    return a*a + b*b


def gaussian_divmod(z, w):
    a, b = pair(z)
    c, d = pair(w)
    denominator = c*c + d*d
    if denominator == 0:
        raise ValueError("division by zero")
    def nearest(x):
        y = x + Fraction(1, 2)
        return y.numerator // y.denominator
    q = (nearest(Fraction(a*c + b*d, denominator)),
         nearest(Fraction(b*c - a*d, denominator)))
    x, y = gaussian_mul(q, w)
    return q, (a-x, b-y)


def minus5_mul(z, w):
    a, b = pair(z)
    c, d = pair(w)
    return a*c - 5*b*d, a*d + b*c


def minus5_norm(z):
    a, b = pair(z)
    return a*a + 5*b*b


def minus5_norm_solutions(n):
    n = integer(n)
    if n < 0:
        raise ValueError("norm cannot be negative")
    if n > 10000:
        raise ValueError("example bound: norm <= 10000")
    # Bounds are mathematically exhaustive for a^2 + 5b^2 = n.
    bound_a, bound_b = isqrt(n), isqrt(n // 5)
    return tuple((a, b) for a in range(-bound_a, bound_a + 1)
                 for b in range(-bound_b, bound_b + 1) if a*a + 5*b*b == n)


def polynomial(f):
    if not isinstance(f, tuple) or not f or len(f) > 64:
        raise ValueError("coefficient tuple must have length 1..64")
    return tuple(integer(v) for v in f)


def content(f):
    answer = 0
    for c in polynomial(f):
        answer = gcd(answer, c)
    return answer  # The zero polynomial has content 0, not primitive.


def poly_mul(f, g):
    f, g = polynomial(f), polynomial(g)
    if len(f) + len(g) - 1 > 64:
        raise ValueError("product exceeds coefficient bound")
    h = [0] * (len(f) + len(g) - 1)
    for i, a in enumerate(f):
        for j, b in enumerate(g):
            h[i+j] += a*b
    return tuple(h)


def write_d4_svg(path):
    _, d4, r, s = examples()
    h = d4.generated((s,))
    names, a = {}, d4.identity
    for k in range(4):
        for epsilon in range(2):
            names[compose(a, s) if epsilon else a] = (
                "e" if k == 0 else ("r" if k == 1 else f"r^{k}")) + ("s" if epsilon else "")
        a = compose(r, a)
    names[s] = "s"
    rows, a = [], d4.identity
    for k in range(4):
        rows.append(sorted((names[compose(a, x)] for x in h), key=lambda n: "s" in n))
        a = compose(r, a)
    fragments = ['<svg xmlns="http://www.w3.org/2000/svg" width="760" height="420" viewBox="0 0 760 420" role="img" aria-labelledby="title desc">',
                 '<title id="title">D4 left cosets of a reflection subgroup</title>',
                 '<desc id="desc">Four rows show r^k H={r^k,r^k s}. Conjugation sends s to r^2 s outside H. These rows do not define quotient multiplication.</desc>',
                 '<rect width="760" height="420" fill="#f8fafc"/>',
                 '<g font-family="sans-serif" font-size="22" fill="#0f172a">',
                 '<text x="28" y="38">D4: |G|=8, H={e,s}, left cosets r^k H</text>']
    for k, row in enumerate(rows):
        y = 65 + k*65
        fragments.extend([f'<rect x="28" y="{y}" width="410" height="52" rx="10" fill="#dbeafe"/>',
                          f'<text x="48" y="{y+34}">k={k}:  {{ {row[0]}, {row[1]} }}</text>'])
    target = names[compose(compose(r, s), inverse(r))]
    fragments.extend(['<text x="470" y="140">r s r^-1 = '+target+'</text>',
                      '<text x="470" y="180">'+target+' is outside H</text>',
                      '<text x="28" y="378">Coset partition exists; H is not normal.</text>',
                      '<text x="28" y="407">No quotient multiplication on these four rows.</text>', '</g>', '</svg>'])
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(fragments) + "\n", encoding="utf-8")


def demo():
    s3, d4, r, s = examples()
    reflection, rotation = d4.generated((s,)), d4.generated((r,))
    return {
        "S3": {"order": len(s3.elements), "subgroups": len(s3.all_subgroups()),
               "n2": len(s3.sylow(2)), "n3": len(s3.sylow(3))},
        "D4": {"order": len(d4.elements), "subgroups": len(d4.all_subgroups()),
               "reflection_normal": d4.is_normal(reflection),
               "reflection_coset_sizes": [len(c) for c in d4.left_cosets(reflection)],
               "rotation_quotient": d4.quotient_table(rotation)},
        "Gaussian_division": gaussian_divmod((7, 5), (3, 2)),
        "minus5_two_factorizations": [minus5_mul((2, 0), (3, 0)), minus5_mul((1, 1), (1, -1))],
        "minus5_norm_2_or_3": [minus5_norm_solutions(2), minus5_norm_solutions(3)],
        "Gauss_contents": [content((2, 2)), content((1, -1)), content(poly_mul((2, 2), (1, -1)))],
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--svg", help="write deterministic D4 coset SVG to this path")
    args = parser.parse_args()
    if args.svg:
        write_d4_svg(args.svg)
    print(json.dumps(demo(), ensure_ascii=False, indent=2))
